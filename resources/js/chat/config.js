// Единая точка получения данных из DOM
export function loadChatConfig() {
    const el = document.getElementById('chat-config');
    if (!el) throw new Error('Chat config element not found');
    return {
        chatId: Number(el.dataset.chatId),
        chatType: el.dataset.chatType || 'group',
        topicId: el.dataset.topicId ? Number(el.dataset.topicId) : null,
        userId: Number(el.dataset.userId),
        currentRole: el.dataset.currentRole || 'member',
        allowCopyMessages: el.dataset.allowCopyMessages !== '0',
        allowForwardMessages: el.dataset.allowForwardMessages !== '0',
        reportUrl: el.dataset.reportUrl || '',
        userName: el.dataset.userName || '',
        firstUnreadId: el.dataset.firstUnread ? Number(el.dataset.firstUnread) : null,
        mutedUntil: el.dataset.mutedUntil || null,
        sendUrl: el.dataset.sendUrl,
        csrfToken: el.dataset.csrf,
        translations: {
            edit: el.dataset.translateEdit,
            delete: el.dataset.translateDelete,
            reply: el.dataset.translateReply,
            send: el.dataset.translateSend,
            save: el.dataset.translateSave,
            copy: el.dataset.translateCopy,
            download: el.dataset.translateDownload,
            messageDeleted: el.dataset.translateMessageDeleted,
            deleteConfirm: el.dataset.translateDeleteConfirm,
            sendError: el.dataset.translateSendError,
            you: el.dataset.translateYou,
            topicNamePrompt: el.dataset.translateTopicNamePrompt,
            topicCreateError: el.dataset.translateTopicCreateError,
            voicePlay: el.dataset.translateVoicePlay,
            voiceLoading: el.dataset.translateVoiceLoading,
            voiceError: el.dataset.translateVoiceError,
            voiceTranscribe: el.dataset.translateVoiceTranscribe,
            voiceTranscribing: el.dataset.translateVoiceTranscribing,
            voiceTranscriptHide: el.dataset.translateVoiceTranscriptHide,
            voiceTranscriptError: el.dataset.translateVoiceTranscriptError,
            voiceTranscriptConsent: el.dataset.translateVoiceTranscriptConsent,
            voiceRecord: el.dataset.translateVoiceRecord,
            voiceStop: el.dataset.translateVoiceStop,
            attachFile: el.dataset.translateAttachFile,
            mediaLoading: el.dataset.translateMediaLoading,
            mediaError: el.dataset.translateMediaError,
            mediaDownload: el.dataset.translateMediaDownload,
            roleMember: el.dataset.translateRoleMember,
            roleModerator: el.dataset.translateRoleModerator,
            roleAdmin: el.dataset.translateRoleAdmin,
            pin: el.dataset.translatePin,
            unpin: el.dataset.translateUnpin,
            pinnedMessages: el.dataset.translatePinnedMessages,
            mutedUntil: el.dataset.translateMutedUntil,
            notificationsEnabled: el.dataset.translateNotificationsEnabled,
            pollCreate: el.dataset.translatePollCreate,
            pollQuestion: el.dataset.translatePollQuestion,
            pollOptions: el.dataset.translatePollOptions,
            pollOptionsHint: el.dataset.translatePollOptionsHint,
            pollAnonymous: el.dataset.translatePollAnonymous,
            pollOpen: el.dataset.translatePollOpen,
            pollClosed: el.dataset.translatePollClosed,
            pollMultiple: el.dataset.translatePollMultiple,
            pollVote: el.dataset.translatePollVote,
            pollVoters: el.dataset.translatePollVoters,
            pollClose: el.dataset.translatePollClose,
            pollError: el.dataset.translatePollError,
            pollValidation: el.dataset.translatePollValidation,
            openFullscreen: el.dataset.translateOpenFullscreen,
            searchMessages: el.dataset.translateSearchMessages,
            videoNoteRecord: el.dataset.translateVideoNoteRecord,
            videoNoteStop: el.dataset.translateVideoNoteStop,
            videoNoteError: el.dataset.translateVideoNoteError
        },
    };
}